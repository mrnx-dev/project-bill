import { format } from "date-fns";
import { id as localeId, enUS as localeEn } from "date-fns/locale";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import remarkBreaks from "remark-breaks";
import rehypeSanitize from "rehype-sanitize";

export type ContractDocumentProps = {
  language: string;                 // normalized internally: anything but "en" renders Indonesian
  contractNumber: string | null;
  title: string;                    // project title
  createdAt: string;                // ISO; the header "Tanggal" — never `new Date()`, a signed paper must reprint identically
  provider: { name: string; address: string | null; email: string | null; whatsapp: string | null };
  client: { name: string; email: string | null; phone: string | null };
  items: { description: string; quantity: number | null; rate: number | null; price: number }[];
  totalPrice: number;
  currency: string;
  taxName: string | null;
  taxRate: number | null;
  dpAmount: number | null;
  billingMode: string;               // "SIMPLE" | "MILESTONE"
  milestones: { name: string; percentage: number; amount: number; dueDate: string | null }[];
  deadline: string | null;           // ISO date
  terms: string;                     // Markdown; never empty (callers 404/400 first)
  termsAcceptedAt: string | null;
  termsAcceptedUserAgent: string | null;
  termsAcceptedSessionId: string | null;
};

// Server-safe presentational component: no "use client", no hooks, no fetching.
// All Decimal/Date conversion must have happened in toContractDocumentProps().
export function ContractDocument(props: ContractDocumentProps) {
  const lang = props.language === "en" ? "en" : "id";
  const dateLocale = lang === "id" ? localeId : localeEn;
  const dateFormat = lang === "id" ? "d MMM yyyy" : "MMM d, yyyy";

  const labels = lang === "id"
    ? {
        docTitle: "Surat Perjanjian Kerja (SPK)",
        no: "No.",
        date: "Tanggal",
        signatureTitle: "Tanda Tangan Elektronik - Jejak Audit",
        acceptedBy: "Disetujui Oleh",
        timestamp: "Stempel Waktu (UTC)",
        userAgent: "User Agent",
        sessionVerify: "Verifikasi ID Sesi",
        disclaimerText: "Dokumen ini berfungsi sebagai perjanjian digital aman yang dihasilkan oleh Corez. Jejak audit di atas memvalidasi nirsangkal (non-repudiation) dari pihak-pihak yang menyepakati kontrak.",
      }
    : {
        docTitle: "Statement of Work",
        no: "No.",
        date: "Date",
        signatureTitle: "Electronic Signature - Audit Trail",
        acceptedBy: "Accepted By",
        timestamp: "Timestamp (UTC)",
        userAgent: "User Agent",
        sessionVerify: "Session ID Verification",
        disclaimerText: "This document serves as a secure digital agreement generated by Corez. The audit trail above validates non-repudiation of the contracting parties.",
      };


  return (
    <div className="bg-white text-slate-900 p-8 md:p-12 mx-auto max-w-[21cm]">
      <div className="print-content block">
        <div className="flex justify-between items-start border-b border-slate-200 pb-8 mb-8">
          <div>
            <h1 className="text-3xl font-serif font-bold mb-2 text-slate-800 tracking-tight">{labels.docTitle}</h1>
            <h2 className="text-xl font-medium text-slate-600 tracking-tight">{props.title}</h2>
          </div>
          <div className="text-right text-sm text-slate-500 flex flex-col gap-1">
            {props.contractNumber && (
              <p><strong className="text-slate-700">{labels.no}</strong> {props.contractNumber}</p>
            )}
            <p><strong className="text-slate-700">{labels.date}</strong> {format(new Date(props.createdAt), dateFormat, { locale: dateLocale })}</p>
          </div>
        </div>



        <section className="mb-16">
          <div className="prose prose-sm max-w-none text-slate-800 leading-relaxed text-justify">
            <ReactMarkdown remarkPlugins={[remarkGfm, remarkBreaks]} rehypePlugins={[rehypeSanitize]}>
              {props.terms}
            </ReactMarkdown>
          </div>
        </section>

        {props.termsAcceptedAt && (
          <div className="mt-16 pt-6 border-t-2 border-slate-900 break-inside-avoid">
            <h3 className="font-bold text-lg mb-4 text-slate-900">{labels.signatureTitle}</h3>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-y-4 gap-x-8 text-sm text-slate-700">
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.acceptedBy}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full">{props.client.name}</span>
              </div>
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.timestamp}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full text-xs font-mono">{props.termsAcceptedAt}</span>
              </div>
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.userAgent}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full text-[10px] break-all truncate" title={props.termsAcceptedUserAgent || "Unknown"}>{props.termsAcceptedUserAgent || "Unknown"}</span>
              </div>
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.sessionVerify}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full text-xs font-mono break-all">{props.termsAcceptedSessionId || "Unknown"}</span>
              </div>
            </div>

            <p className="mt-8 text-[11px] text-slate-400 text-center italic">
              {labels.disclaimerText}
            </p>
          </div>
        )}
      </div>
    </div>
  );
}
