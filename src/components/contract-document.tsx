import { format } from "date-fns";
import { id as localeId, enUS as localeEn } from "date-fns/locale";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import remarkBreaks from "remark-breaks";
import rehypeSanitize from "rehype-sanitize";
import { formatMoney, getCurrency } from "@/lib/currency";

export type ContractDocumentProps = {
  language: string;                 // normalized internally: anything but "en" renders Indonesian
  contractNumber: string | null;
  title: string;                    // project title
  createdAt: string;                // ISO; the header "Tanggal" — never `new Date()`, a signed paper must reprint identically
  provider: { name: string; address: string | null; email: string | null; whatsapp: string | null };
  client: { name: string; email: string | null; phone: string | null };
  items: { description: string; quantity: number | null; rate: number | null; price: number }[];
  totalPrice: number;
  currency: string;
  taxName: string | null;
  taxRate: number | null;
  dpAmount: number | null;
  billingMode: string;               // "SIMPLE" | "MILESTONE"
  milestones: { name: string; percentage: number; amount: number; dueDate: string | null }[];
  deadline: string | null;           // ISO date
  terms: string;                     // Markdown; never empty (callers 404/400 first)
  termsAcceptedAt: string | null;
  termsAcceptedUserAgent: string | null;
  termsAcceptedSessionId: string | null;
};

// Server-safe presentational component: no "use client", no hooks, no fetching.
// All Decimal/Date conversion must have happened in toContractDocumentProps().
export function ContractDocument(props: ContractDocumentProps) {
  const lang = props.language === "en" ? "en" : "id";
  const dateLocale = lang === "id" ? localeId : localeEn;
  const dateFormat = lang === "id" ? "d MMM yyyy" : "MMM d, yyyy";
  const money = (n: number) => formatMoney(n, props.currency);
  // Round to the currency's minor units: plain Math.round kills the cents on USD/EUR tax.
  const roundedMoney = (n: number) =>
    formatMoney(Number(Math.round((n + Number.EPSILON) * 10 ** getCurrency(props.currency).decimals)) / 10 ** getCurrency(props.currency).decimals, props.currency);

  const labels = lang === "id"
    ? {
        docTitle: "Surat Perjanjian Kerja (SPK)",
        enDocTitle: "Statement of Work",
        no: "No.",
        date: "Tanggal",
        provider: "Penyedia Jasa",
        client: "Klien",
        scope: "1. Lingkup Pekerjaan & Deliverables",
        desc: "Deskripsi",
        qty: "Qty",
        rate: "Harga Satuan",
        price: "Harga",
        itemTotal: "Total",
        agreedTotal: "Total pekerjaan yang disepakati",
        schedule: "2. Jadwal Pelaksanaan",
        deadline: "Batas Waktu Penyelesaian",
        milestoneName: "Tahap",
        milestonePct: "Persentase",
        milestoneAmount: "Nilai",
        milestoneDue: "Jatuh Tempo",
        payment: "3. Harga & Termin Pembayaran",
        tax: "Pajak",
        dp: "Uang Muka (DP) Awal",
        terms: "4. Syarat & Ketentuan",
        signatureTitle: "Tanda Tangan Elektronik - Jejak Audit",
        acceptedBy: "Disetujui Oleh",
        timestamp: "Stempel Waktu (UTC)",
        userAgent: "User Agent",
        sessionVerify: "Verifikasi ID Sesi",
        disclaimerText: "Dokumen ini berfungsi sebagai perjanjian digital aman yang dihasilkan oleh ProjectBill. Jejak audit di atas memvalidasi nirsangkal (non-repudiation) dari pihak-pihak yang menyepakati kontrak.",
      }
    : {
        docTitle: "Statement of Work",
        enDocTitle: "Surat Perjanjian Kerja (SPK)",
        no: "No.",
        date: "Date",
        provider: "Provider",
        client: "Client",
        scope: "1. Scope of Work & Deliverables",
        desc: "Description",
        qty: "Qty",
        rate: "Rate",
        price: "Price",
        itemTotal: "Total",
        agreedTotal: "Agreed total for the work described",
        schedule: "2. Schedule",
        deadline: "Completion Deadline",
        milestoneName: "Milestone",
        milestonePct: "Percentage",
        milestoneAmount: "Amount",
        milestoneDue: "Due Date",
        payment: "3. Price & Payment Terms",
        tax: "Tax",
        dp: "Initial Down Payment (DP)",
        terms: "4. Terms & Conditions",
        signatureTitle: "Electronic Signature - Audit Trail",
        acceptedBy: "Accepted By",
        timestamp: "Timestamp (UTC)",
        userAgent: "User Agent",
        sessionVerify: "Session ID Verification",
        disclaimerText: "This document serves as a secure digital agreement generated by ProjectBill. The audit trail above validates non-repudiation of the contracting parties.",
      };

  // Single typed array: provider and client have different shapes, so mapping over a union
  // of them fails tsc (Property 'address' does not exist on type '…').
  const parties: { role: string; name: string; lines: (string | null)[] }[] = [
    { role: labels.provider, name: props.provider.name, lines: [props.provider.address, props.provider.email, props.provider.whatsapp] },
    { role: labels.client, name: props.client.name, lines: [props.client.email, props.client.phone] },
  ];

  const hasItems = props.items.length > 0;

  return (
    <div className="bg-white text-slate-900 p-8 md:p-12 mx-auto max-w-[21cm]">
      <div className="print-content block">
        <div className="flex justify-between items-start border-b border-slate-200 pb-8 mb-8">
          <div>
            <h1 className="text-3xl font-serif font-bold mb-2 text-slate-800 tracking-tight">{labels.docTitle}</h1>
            <h2 className="text-xl font-medium text-slate-600 tracking-tight">{props.title}</h2>
          </div>
          <div className="text-right text-sm text-slate-500 flex flex-col gap-1">
            {props.contractNumber && (
              <p><strong className="text-slate-700">{labels.no}</strong> {props.contractNumber}</p>
            )}
            <p><strong className="text-slate-700">{labels.date}</strong> {format(new Date(props.createdAt), dateFormat, { locale: dateLocale })}</p>
          </div>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-6 mb-12">
          {parties.map((party) => (
            <div key={party.role} className="border border-slate-200 rounded-md p-4">
              <p className="text-xs font-bold uppercase tracking-wide text-slate-400 mb-2">{party.role}</p>
              <p className="font-semibold text-slate-900">{party.name}</p>
              {party.lines.filter((l) => l !== null).map((line, i) => (
                <p key={i} className="text-sm text-slate-600">{line}</p>
              ))}
            </div>
          ))}
        </div>

        <section className="mb-12">
          <h3 className="font-bold text-lg mb-4 text-slate-900">{labels.scope}</h3>
          {hasItems ? (
            <table className="w-full text-sm border-collapse">
              <thead className="border-b-2 border-slate-900">
                <tr>
                  <th className="text-left py-2 pr-2">{labels.desc}</th>
                  <th className="text-right py-2 px-2">{labels.qty}</th>
                  <th className="text-right py-2 px-2">{labels.rate}</th>
                  <th className="text-right py-2 pl-2">{labels.price}</th>
                </tr>
              </thead>
              <tbody>
                {props.items.map((item, i) => (
                  <tr key={i} className="border-b border-slate-200 break-inside-avoid">
                    <td className="py-2 pr-2 text-justify">{item.description}</td>
                    <td className="py-2 px-2 text-right">{item.quantity ?? "-"}</td>
                    <td className="py-2 px-2 text-right">{item.rate !== null ? money(item.rate) : "-"}</td>
                    <td className="py-2 pl-2 text-right whitespace-nowrap">{money(item.price)}</td>
                  </tr>
                ))}
                <tr className="font-semibold break-inside-avoid">
                  <td className="py-2 pr-2" colSpan={3}>{labels.itemTotal}</td>
                  <td className="py-2 pl-2 text-right whitespace-nowrap">{money(props.totalPrice)}</td>
                </tr>
              </tbody>
            </table>
          ) : (
            <p className="text-sm text-slate-700">
              {labels.agreedTotal}: <strong>{money(props.totalPrice)}</strong>
            </p>
          )}
        </section>

        {(props.deadline || props.billingMode === "MILESTONE") && (
          <section className="mb-12">
            <h3 className="font-bold text-lg mb-4 text-slate-900">{labels.schedule}</h3>
            {props.deadline && (
              <p className="text-sm text-slate-700 mb-4">
                <span className="font-semibold">{labels.deadline}:</span>{" "}
                {format(new Date(props.deadline), dateFormat, { locale: dateLocale })}
              </p>
            )}
            {props.billingMode === "MILESTONE" && props.milestones.length > 0 && (
              <table className="w-full text-sm border-collapse">
                <thead className="border-b-2 border-slate-900">
                  <tr>
                    <th className="text-left py-2 pr-2">{labels.milestoneName}</th>
                    <th className="text-right py-2 px-2">{labels.milestonePct}</th>
                    <th className="text-right py-2 px-2">{labels.milestoneAmount}</th>
                    <th className="text-right py-2 pl-2">{labels.milestoneDue}</th>
                  </tr>
                </thead>
                <tbody>
                  {props.milestones.map((m, i) => (
                    <tr key={i} className="border-b border-slate-200 break-inside-avoid">
                      <td className="py-2 pr-2">{m.name}</td>
                      <td className="py-2 px-2 text-right">{m.percentage}%</td>
                      <td className="py-2 px-2 text-right whitespace-nowrap">{money(m.amount)}</td>
                      <td className="py-2 pl-2 text-right">{m.dueDate ? format(new Date(m.dueDate), dateFormat, { locale: dateLocale }) : "-"}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </section>
        )}

        <section className="mb-12">
          <h3 className="font-bold text-lg mb-4 text-slate-900">{labels.payment}</h3>
          <div className="text-sm text-slate-700 space-y-2">
            <p className="flex justify-between border-b border-slate-200 pb-2 break-inside-avoid">
              <span className="font-semibold">{labels.itemTotal}</span>
              <span className="whitespace-nowrap">{money(props.totalPrice)}</span>
            </p>
            {props.taxRate !== null && (
              <p className="flex justify-between border-b border-slate-200 pb-2 break-inside-avoid">
                <span>{props.taxName || labels.tax} ({props.taxRate}%)</span>
                <span className="whitespace-nowrap">{roundedMoney(props.totalPrice * props.taxRate / 100)}</span>
              </p>
            )}
            {props.billingMode !== "MILESTONE" && props.dpAmount !== null && props.dpAmount > 0 && (
              <p className="flex justify-between border-b border-slate-200 pb-2 break-inside-avoid">
                <span>{labels.dp}</span>
                <span className="whitespace-nowrap">{money(props.dpAmount)}</span>
              </p>
            )}
          </div>
        </section>

        <section className="mb-16">
          <h3 className="font-bold text-lg mb-4 text-slate-900">{labels.terms}</h3>
          <div className="prose prose-sm max-w-none text-slate-800 leading-relaxed text-justify break-inside-avoid">
            <ReactMarkdown remarkPlugins={[remarkGfm, remarkBreaks]} rehypePlugins={[rehypeSanitize]}>
              {props.terms}
            </ReactMarkdown>
          </div>
        </section>

        {props.termsAcceptedAt && (
          <div className="mt-16 pt-6 border-t-2 border-slate-900 break-inside-avoid">
            <h3 className="font-bold text-lg mb-4 text-slate-900">{labels.signatureTitle}</h3>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-y-4 gap-x-8 text-sm text-slate-700">
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.acceptedBy}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full">{props.client.name}</span>
              </div>
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.timestamp}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full text-xs font-mono">{props.termsAcceptedAt}</span>
              </div>
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.userAgent}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full text-[10px] break-all truncate" title={props.termsAcceptedUserAgent || "Unknown"}>{props.termsAcceptedUserAgent || "Unknown"}</span>
              </div>
              <div>
                <span className="block font-semibold text-slate-900 mb-1">{labels.sessionVerify}</span>
                <span className="bg-slate-100 px-3 py-1.5 rounded inline-block w-full text-xs font-mono break-all">{props.termsAcceptedSessionId || "Unknown"}</span>
              </div>
            </div>

            <p className="mt-8 text-[11px] text-slate-400 text-center italic">
              {labels.disclaimerText}
            </p>
          </div>
        )}
      </div>
    </div>
  );
}
